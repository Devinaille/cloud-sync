func TestMergeAndSave_UpdatesAndPreservesComments(t *testing.T) {
	preserveEnv(t)
	path := filepath.Join(t.TempDir(), "cloud-sync.yaml")
	existing := "# keep this header\n" +
		"openlist_url: \"http://old\"\n" +
		"openlist_token: \"secret\"\n" +
		"watch_dirs:\n  - /old/dir\n" +
		"# keep the concurrency comment\n" +
		"upload_concurrency: 9\n"
	if err := os.WriteFile(path, []byte(existing), 0o644); err != nil {
		t.Fatal(err)
	}

	v := fullForm(t)
	v.OpenListToken = "" // keep existing token
	v.OpenListURL = "http://new"

	if err := MergeAndSave(path, v); err != nil {
		t.Fatalf("MergeAndSave: %v", err)
	}
	out, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)
	for _, want := range []string{
		"# keep this header",
		"# keep the concurrency comment",
		"http://new",
		"secret",
		"upload_concurrency: 2",
		"cleanup_dry_run: false", // key absent before, added
	} {
		if !strings.Contains(s, want) {
			t.Errorf("merged yaml missing %q:\n%s", want, s)
		}
	}
	if strings.Contains(s, "/old/dir") {
		t.Errorf("watch_dirs not replaced:\n%s", s)
	}

	got, err := Load(path)
	if err != nil {
		t.Fatalf("Load merged: %v", err)
	}
	if got.OpenListURL != "http://new" || got.OpenListToken != "secret" {
		t.Errorf("loaded url/token = %q/%q", got.OpenListURL, got.OpenListToken)
	}
	if got.UploadConcurrency != 2 {
		t.Errorf("upload_concurrency = %d, want 2", got.UploadConcurrency)
	}
}

