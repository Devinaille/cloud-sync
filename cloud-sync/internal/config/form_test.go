func TestSaveRaw_ValidatesBeforeReplacing(t *testing.T) {
	preserveEnv(t)
	path := filepath.Join(t.TempDir(), "cloud-sync.yaml")
	if err := os.WriteFile(path, []byte("log_level: info\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	// Invalid (missing required keys) must fail and leave the file untouched.
	if err := SaveRaw(path, []byte("log_level: info\n")); err == nil {
		t.Fatal("SaveRaw(invalid) = nil, want error")
	}
	cur, _ := os.ReadFile(path)
	if string(cur) != "log_level: info\n" {
		t.Errorf("file changed after failed save: %q", cur)
	}

	// A valid document (generated by MergeAndSave) replaces the file.
	if err := MergeAndSave(path, fullForm(t)); err != nil {
		t.Fatalf("MergeAndSave: %v", err)
	}
	good, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := SaveRaw(path, good); err != nil {
		t.Fatalf("SaveRaw(valid): %v", err)
	}
	if _, err := Load(path); err != nil {
		t.Fatalf("Load saved: %v", err)
	}
}

func TestRender_ParsesAndHasComments(t *testing.T) {
	preserveEnv(t)
	dir := t.TempDir()
	cfg := &Config{
		OpenListURL: "http://openlist:5244", OpenListToken: "tok",
		SrcStorage: "/local_media", DstStorage: "/139yun_media",
		WatchDirs: []string{dir}, SyncStatusDir: filepath.Join(dir, ".sync_status"),
		AllowedPrefixes: []string{dir}, CleanupAfter: 72 * time.Hour,
		UploadConcurrency: 2, StabilizeWait: 30 * time.Second, PollInterval: 3 * time.Second,
		TaskTimeout: 1800 * time.Second, LogLevel: "info", UIListen: ":8099",
		CleanupInterval: 3600 * time.Second,
	}
	out, err := Render(cfg)
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !strings.Contains(string(out), "#") {
		t.Errorf("Render output has no comments:\n%s", out)
	}
	path := filepath.Join(t.TempDir(), "cloud-sync.yaml")
	if err := os.WriteFile(path, out, 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Load(path); err != nil {
		t.Fatalf("Load(Render output): %v", err)
	}
}

